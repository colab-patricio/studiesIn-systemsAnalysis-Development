"""Q5. Faça um programa que receba um número inteiro e verifique se esse número é par ou ímpar.
"""

numero = int(input("Digite um número inteiro: "))

# Solução por estrutura condicional
if numero % 2 == 0:
    print("O número é par.")
else:
    print("O número é ímpar.")